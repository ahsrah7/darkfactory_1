import { readdirSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

// PR-2 (SCRUM-7): checks the first migration's SQL as text. No database is used.
const here = dirname(fileURLToPath(import.meta.url));
const migrationsDir = resolve(here, "../../../migrations");

const migrationFolders = readdirSync(migrationsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && entry.name.endsWith("_init_todo"))
  .map((entry) => entry.name)
  .sort();

if (migrationFolders.length !== 1) {
  throw new Error(
    `expected exactly one *_init_todo migration folder, found ${migrationFolders.length}`,
  );
}

const migrationFolder = migrationFolders[0] ?? "";
const sql = readFileSync(
  resolve(migrationsDir, migrationFolder, "migration.sql"),
  "utf8",
);

// Body lines of CREATE TABLE "Todo", with trailing commas removed.
const createTable = /CREATE TABLE "Todo" \(\r?\n([\s\S]*?)\r?\n\);/.exec(sql);
const tableLines = (createTable?.[1] ?? "")
  .split(/\r?\n/)
  .map((line) => line.trim().replace(/,$/, ""))
  .filter((line) => line !== "");

function columnLine(name: string): string | undefined {
  return tableLines.find((line) => line.startsWith(`"${name}" `));
}

describe("Todo migration (PR-2)", () => {
  it("the migration folder uses Prisma's timestamp format and is named init_todo", () => {
    expect(migrationFolder).toMatch(/^\d{14}_init_todo$/);
  });

  it('creates exactly one table, named "Todo"', () => {
    expect(createTable).not.toBeNull();
    expect(sql.match(/CREATE TABLE/g)).toHaveLength(1);
  });

  it("creates exactly the designed columns and primary key", () => {
    expect(tableLines).toEqual([
      '"id" UUID NOT NULL DEFAULT gen_random_uuid()',
      '"title" VARCHAR(200) NOT NULL',
      '"completed" BOOLEAN NOT NULL DEFAULT false',
      '"createdAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP',
      '"updatedAt" TIMESTAMPTZ NOT NULL',
      'CONSTRAINT "Todo_pkey" PRIMARY KEY ("id")',
    ]);
  });

  it("title is VARCHAR(200), not TEXT", () => {
    expect(columnLine("title")).toBe('"title" VARCHAR(200) NOT NULL');
    expect(sql).not.toMatch(/"title"\s+TEXT/);
  });

  it("id is UUID, generated by the database, and the primary key", () => {
    expect(columnLine("id")).toBe(
      '"id" UUID NOT NULL DEFAULT gen_random_uuid()',
    );
    expect(sql).toContain('CONSTRAINT "Todo_pkey" PRIMARY KEY ("id")');
  });

  it("completed is a non-null boolean that defaults to false", () => {
    expect(columnLine("completed")).toBe(
      '"completed" BOOLEAN NOT NULL DEFAULT false',
    );
  });

  it("createdAt and updatedAt are non-null timestamptz columns", () => {
    expect(columnLine("createdAt")).toBe(
      '"createdAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP',
    );
    expect(columnLine("updatedAt")).toBe('"updatedAt" TIMESTAMPTZ NOT NULL');
  });
});
